from typing import Protocol
from datetime import datetime
from app.models import Measurement, Event, Weather, Advice, State, Feedback, Ask, Reply, Query, Intent

class Problem(Exception):
    def __init__(self, code: str, message: str, http: int = 502):
        self.code, self.message, self.http = code, message, http
        super().__init__(message)


class WeatherProvider(Protocol):
    def weather(self, q: Query) -> Weather: ...


class RecommendationProvider(Protocol):
    def advice(self, intent: Intent, indoor: Measurement | None, weather: Weather | None,
               state: State | None, preferences: dict | None = None) -> Advice: ...


class EventProvider(Protocol):
    def events(self, room_id: str) -> list[Event]: ...
    def event(self, event_id: str) -> Event: ...


class Provider(WeatherProvider, RecommendationProvider, EventProvider, Protocol):
    def latest(self, q: Query) -> Measurement | None: ...
    def history(self, q: Query, start: datetime, end: datetime) -> list[Measurement]: ...
    def device_state(self, room_id: str) -> State: ...
    def ask(self, data: Ask) -> Feedback: ...
    def reply(self, fid: str, data: Reply) -> Feedback: ...
    def feedback(self, fid: str) -> Feedback: ...
    def feedback_list(self, event_id: str) -> list[Feedback]: ...
    def revisions(self, fid: str) -> list[Feedback]: ...
